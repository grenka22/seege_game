namespace Seega.Contracts;

/// <summary>
/// Идентификатор игрока, а также состояние клетки на игровом поле.
/// Используется во всех слоях проекта:
/// 1. В UI — для отображения имени и цвета текущего игрока.
/// 2. В BL — для контроля очередности ходов и проверки принадлежности фишек.
/// 3. В Data — для компактного сохранения доски в JSON.
/// Базовый тип 'byte' выбран для оптимизации памяти (1 байт на клетку вместо 4 байт у int).
/// </summary>
public enum PlayerId : byte
{
    /// <summary>
    /// Ничейная позиция, отсутствие игрока или пустая клетка на поле.
    /// Значение 0 является значением по умолчанию в C#.
    /// </summary>
    None = 0,

    /// <summary>
    /// Первый игрок.
    /// На доске обычно отображается как 'X' (белые фишки).
    /// Первым начинает фазу расстановки фишек (Placement Phase).
    /// </summary>
    Player1 = 1,

    /// <summary>
    /// Второй игрок.
    /// На доске обычно отображается как 'O' (чёрные фишки).
    /// По правилам Сеги первым начинает фазу движения фишек (Movement Phase).
    /// </summary>
    Player2 = 2
}