namespace Seega.Contracts;

/// <summary>
/// Интерфейс (контракт) репозитория для работы с таблицей рекордов.
/// Определяет правила сохранения результатов партий и получения топа лучших игроков.
/// Реализуется в слое Data, используется в UI и BL.
/// </summary>
public interface IRecordRepository
{
    /// <summary>
    /// Добавляет результат завершенной партии в постоянное хранилище (в файл рекордов).
    /// </summary>
    /// <param name="record">Объект с данными о сыгранной партии (участники, победитель, счёт, дата).</param>
    void AddRecord(GameRecord record);

    /// <summary>
    /// Возвращает список лучших результатов, отсортированных по убыванию очков.
    /// </summary>
    /// <param name="count">Количество записей для выборки (требуется показывать топ-5).</param>
    /// <returns>Коллекция лучших записей только для чтения (защищена от случайного изменения снаружи).</returns>
    IReadOnlyList<GameRecord> GetTopRecords(int count);
}