using Seega.Contracts;

namespace Seega.Business;

/// <summary>
/// Представляет одно игровое действие (ход), совершенное игроком.
/// Объект хода используется для фиксации истории партии, 
/// отображения в UI и работы механизма отмены хода (Undo).
/// </summary>
public class Move
{
    /// <summary>
    /// Игрок, совершивший этот ход (Player1 или Player2).
    /// </summary>
    public PlayerId Player { get; set; }

    /// <summary>
    /// Исходная клетка, откуда переместилась фишка.
    /// <para>
    /// Внимание (Nullable): свойство равно <c>null</c> на фазе расстановки (Placement),
    /// так как фишка берется "из руки" игрока, а не с доски.
    /// На фазе перемещения (Movement) здесь всегда хранится реальная координата.
    /// </para>
    /// </summary>
    public BoardCoordinate? From { get; set; }

    /// <summary>
    /// Целевая клетка, куда фишка была поставлена или перемещена.
    /// </summary>
    public BoardCoordinate To { get; set; }

    /// <summary>
    /// Список координат фишек противника, которые были захвачены этим ходом.
    /// <para>
    /// На фазе расстановки список всегда пуст.
    /// На фазе движения может содержать от 0 до 3 клеток (при мульти-захвате клещами).
    /// Необходим для корректного возврата фишек на доску при отмене хода (Undo).
    /// </para>
    /// </summary>
    public List<BoardCoordinate> CapturedPieces { get; set; } = new();
}