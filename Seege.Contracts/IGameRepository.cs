namespace Seega.Contracts;

/// <summary>
/// Интерфейс (контракт) репозитория для сохранения и загрузки состояния партии.
/// Служит мостом между бизнес-логикой (BL) и хранилищем файлов (Data / DAL).
/// Реализуется слоем Data, позволяя изолировать правила игры от деталей записи в файлы и JSON.
/// </summary>
public interface IGameRepository
{
    /// <summary>
    /// Сохраняет текущий снимок игры в постоянное хранилище (например, в файл savegame.json).
    /// </summary>
    /// <param name="state">Полный снимок текущего состояния игры (GameState).</param>
    void SaveGame(GameState state);

    /// <summary>
    /// Загружает ранее сохраненную партию из хранилища.
    /// </summary>
    /// <returns>Восстановленный объект GameState, с которого продолжится игра.</returns>
    GameState LoadGame();

    /// <summary>
    /// Проверяет, существует ли файл с сохраненной ранее партией.
    /// Метод требуется для главного меню (UI): чтобы сделать кнопку "Продолжить игру" активной или заблокированной.
    /// </summary>
    /// <returns>True, если файл сохранения существует и корректен; иначе False.</returns>
    bool HasSavedGame();

    /// <summary>
    /// Удаляет файл сохранения.
    /// Вызывается после официального завершения партии (победа или ничья), 
    /// чтобы нельзя было повторно загрузить уже оконченную игру.
    /// </summary>
    void DeleteSave();
}