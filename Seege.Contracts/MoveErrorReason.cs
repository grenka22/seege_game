namespace Seega.Contracts;

/// <summary>
/// Причины отклонения хода или действия игрока.
/// Используется в MoveResult, чтобы слой UI мог показать понятное сообщение об ошибке.
/// Тип byte выбран для оптимизации памяти при передаче данных.
/// </summary>
public enum MoveErrorReason : byte
{
    /// <summary>
    /// Ошибки нет. Действие выполнено успешно.
    /// </summary>
    None = 0,

    /// <summary>
    /// Указанные координаты находятся за пределами поля 5х5 (вне диапазона A1–E5).
    /// </summary>
    OutOfBounds,

    /// <summary>
    /// Клетка уже занята другой фишкой (актуально для фазы расстановки).
    /// </summary>
    CellOccupied,

    /// <summary>
    /// Попытка поставить фишку в центральную клетку (C3 / индекс 12) на фазе расстановки.
    /// По правилам Сеги центр во время расстановки обязан оставаться пустым.
    /// </summary>
    CenterRestrictedInPlacement,

    /// <summary>
    /// Попытка походить чужой фишкой или выбрать пустую клетку в качестве исходной.
    /// </summary>
    NotPlayerPiece,

    /// <summary>
    /// Клетка назначения уже занята другой фишкой (для фазы движения).
    /// </summary>
    DestinationOccupied,

    /// <summary>
    /// Недопустимый шаг: попытка пойти больше чем на 1 клетку или ход по диагонали 
    /// (в Сеге разрешены перемещения строго на 1 соседнюю клетку по горизонтали или вертикали).
    /// </summary>
    InvalidStepRange,

    /// <summary>
    /// Выбранная фишка заперта: вокруг неё нет ни одной свободной соседней клетки.
    /// </summary>
    PieceHasNoMoves,

    /// <summary>
    /// Нарушение правила комбо: после взятия игрок обязан продолжить ход той же самой фишкой, 
    /// либо явно завершить ход (командой pass).
    /// </summary>
    MustContinueComboWithSamePiece,

    /// <summary>
    /// Попытка сделать ход в уже завершенной партии (один из игроков победил или зафиксирована ничья).
    /// </summary>
    GameAlreadyFinished,

    /// <summary>
    /// Необоснованный пропуск хода: попытка пропустить ход (Pass), 
    /// когда у игрока на самом деле есть доступные ходы и он не находится в блокаде.
    /// </summary>
    NoMovesToPass
}