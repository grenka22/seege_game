using System;

namespace Seega.Contracts;

/// <summary>
/// Представляет координату клетки на доске 5x5.
/// Структура неизменяема (readonly record struct), что гарантирует безопасность данных.
/// </summary>
/// <param name="Row">Индекс строки: от 0 (верх, '1') до 4 (низ, '5').</param>
/// <param name="Col">Индекс столбца: от 0 (лево, 'A') до 4 (право, 'E').</param>
public readonly record struct BoardCoordinate(int Row, int Col)
{
    /// <summary>
    /// Порядковый индекс клетки в плоском одномерном массиве размером 25 элементов (от 0 до 24).
    /// Используется для сохранения в JSON и быстрой работы с доской.
    /// Формула: Row * 5 + Col переводит координаты сетки (строка, колонка) в номер ячейки массива.
    /// </summary>
    public int Index => Row * 5 + Col;

    /// <summary>
    /// Создает координату клетки из порядкового индекса плоского массива (от 0 до 24).
    /// </summary>
    /// <param name="index">Индекс клетки в массиве (0..24).</param>
    /// <returns>Экземпляр координаты с вычисленными строкой и колонкой.</returns>
    public static BoardCoordinate FromIndex(int index) => 
        // Целочисленное деление на 5 дает номер строки (Row).
        // Остаток от деления на 5 дает номер столбца (Col).
        new(index / 5, index % 5);

    /// <summary>
    /// Пытается преобразовать введенный пользователем текст (например, "A1", "c3") в координату.
    /// Безопасный метод: не выбрасывает исключений (крашей), если ввод некорректен.
    /// </summary>
    /// <param name="input">Текст, введенный игроком в консоли.</param>
    /// <param name="coordinate">Полученная координата, если преобразование прошло успешно.</param>
    /// <returns>True, если строка распознана и находится в пределах поля 5х5; иначе False.</returns>
    public static bool TryParse(string? input, out BoardCoordinate coordinate)
    {
        // По умолчанию возвращаем пустую координату (0, 0)
        coordinate = default;

        // Проверка на пустую строку или строку только из пробелов
        if (string.IsNullOrWhiteSpace(input)) return false;

        // Удаляем случайные пробелы по краям и переводим все буквы в верхний регистр (например, " c3 " -> "C3")
        string clean = input.Trim().ToUpperInvariant();

        // Валидная координата должна состоять строго из 2 символов: буквы и цифры (например, 'B' и '4')
        if (clean.Length != 2) return false;

        char colChar = clean[0]; // Буква столбца (A, B, C, D, E)
        char rowChar = clean[1]; // Цифра строки (1, 2, 3, 4, 5)

        // Преобразуем букву в числовой индекс колонки (0..4) с помощью ASCII-арифметики:
        // 'A' - 'A' = 0
        // 'B' - 'A' = 1
        // 'C' - 'A' = 2 и так далее
        int col = colChar - 'A';

        // Преобразуем символ цифры в индекс строки (0..4):
        // '1' - '1' = 0
        // '2' - '1' = 1
        // '5' - '1' = 4
        int row = rowChar - '1';

        // Проверяем, что индексы не вышли за границы доски 5х5 (от 0 до 4)
        if (col is < 0 or > 4 || row is < 0 or > 4) return false;

        // Координата корректна — создаем объект и возвращаем успех
        coordinate = new BoardCoordinate(row, col);
        return true;
    }

    /// <summary>
    /// Преобразует внутренние числовые координаты обратно в понятную игроку строку (например, "C3").
    /// </summary>
    /// <returns>Строка из буквы столбца и номера строки.</returns>
    public override string ToString() => 
        // Прибавляем индекс Col к коду буквы 'A' (получаем 'A', 'B', 'C'...) 
        // и прибавляем 1 к индексу Row (получаем строку от 1 до 5)
        $"{(char)('A' + Col)}{Row + 1}";
}