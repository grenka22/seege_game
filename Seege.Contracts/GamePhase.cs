namespace Seega.Contracts;

/// <summary>
/// Определяет текущую фазу партии в игре.
/// Служит основой для конечного автомата игры и определяет,
/// какие команды и действия игроков разрешены в данный момент.
/// Базовый тип byte оптимизирует потребление памяти и сериализацию в JSON.
/// </summary>
public enum GamePhase : byte
{
    /// <summary>
    /// Фаза 1: Расстановка фишек.
    /// Игроки по очереди выставляют ровно по 2 фишки за один ход на любые свободные клетки.
    /// Центральная клетка поля (C3 / Крепость) на этой фазе строго заблокирована.
    /// Фаза завершается автоматически после выставления всех 24 фишек.
    /// </summary>
    Placement = 0,

    /// <summary>
    /// Фаза 2: Перемещение фишек.
    /// Игроки перемещают свои фишки на 1 клетку по горизонтали или вертикали на свободные ячейки (включая центр C3).
    /// На этой фазе происходят захваты фишек соперника и комбо-серии ходов.
    /// </summary>
    Movement = 1,

    /// <summary>
    /// Завершение игры.
    /// Наступает при победе одного из игроков (у соперника осталось 1 или 0 фишек)
    /// либо при взаимной блокаде (ничья).
    /// Любые дальнейшие ходы блокируются, а итоговый результат передаётся в таблицу рекордов.
    /// </summary>
    Finished = 2
}