using Seega.Contracts;

namespace Seega.Business;

/// <summary>
/// Главный фасад и координатор бизнес-логики игры Сега.
/// Управляет состоянием партии, правилами, очередностью ходов и доской.
/// Предоставляет уровень представления единым API для управления игровым процессом.
/// </summary>
public class GameManager
{
    /// <summary>
    /// Внутренняя модель поля 5x5, отвечающая за хранение фишек и быстрый доступ к клеткам.
    /// </summary>
    private readonly Board _board = new();

    /// <summary>
    /// Текущее состояние игры: фаза, активный игрок, счетчики фишек, история.
    /// </summary>
    private GameState _state = new();

    /// <summary>
    /// Запускает новую партию с начальными настройками по правилам Сеги 5x5.
    /// Сбрасывает доску и готовит игру к первой фазе (расстановка фишек).
    /// </summary>
    /// <param name="p1Name">Имя первого игрока (ходит первым в фазе расстановки).</param>
    /// <param name="p2Name">Имя второго игрока (начинает фазу движения).</param>
    public void StartNewGame(string p1Name, string p2Name)
    {
        // Очищаем все клетки доски (все ячейки становятся пустыми -> None)
        _board.Clear();

        // Формируем начальное состояние партии
        _state = new GameState
        {
            Player1Name = p1Name,
            Player2Name = p2Name,
            Phase = GamePhase.Placement,       // Начинаем с фазы расстановки
            CurrentPlayer = PlayerId.Player1,  // Игрок 1 выставляет фишки первым
            PlacementSubTurn = 1,              // Ставится 1-я фишка из пары текущего игрока
            Player1PiecesToPlace = 12,         // У каждого игрока в запасе по 12 фишек
            Player2PiecesToPlace = 12
        };
    }

    /// <summary>
    /// Выставляет фишку на поле во время фазы расстановки (Фаза 1).
    /// Игроки ставят по 2 фишки за ход на любые клетки, кроме центра C3.
    /// </summary>
    /// <param name="target">Координата клетки, куда игрок хочет поставить фишку.</param>
    /// <returns>Результат действия: успех или причина ошибки (занято, центр и т.д.).</returns>
    public MoveResult PlacePiece(BoardCoordinate target)
    {
        // Заглушка для 1-й недели:
        // Метод объявлен, чтобы компилировался UI.
        // Реальную проверку клетки и выставление фишки мы напишем на 3-й неделе.
        return MoveResult.Fail(MoveErrorReason.None, _state);
    }

    /// <summary>
    /// Перемещает фишку на 1 клетку по ортогонали в фазе движения (Фаза 2)
    /// и запускает алгоритм захвата фишек противника.
    /// </summary>
    /// <param name="from">Откуда ходит фишка (клетка текущего игрока).</param>
    /// <param name="to">Куда ходит фишка (свободная соседняя клетка по горизонтали/вертикали).</param>
    /// <returns>Результат хода: список съеденных фишек, доступность комбо и статус победы.</returns>
    public MoveResult MakeMove(BoardCoordinate from, BoardCoordinate to)
    {
        // Заглушка для 1-й недели:
        // Полноценную проверку шага, зажатия врагов и серии комбо мы напишем на 4-й неделе.
        return MoveResult.Fail(MoveErrorReason.None, _state);
    }

    /// <summary>
    /// Передает ход сопернику в случае блокады (у игрока нет доступных ходов)
    /// либо при добровольном отказе игрока от продолжения серии комбо-взятий.
    /// </summary>
    /// <returns>Результат операции с обновленным активным игроком.</returns>
    public MoveResult PassTurn()
    {
        // Заглушка для 1-й недели:
        // Логику передачи хода при блокаде свяжем с алгоритмом на 4-й и 5-й неделе.
        return MoveResult.Fail(MoveErrorReason.None, _state);
    }

    /// <summary>
    /// Отменяет последний сделанный ход (механика Undo), возвращая состояние на шаг назад.
    /// </summary>
    /// <returns>True, если отмена успешна; False, если история пуста или отмена невозможна.</returns>
    public bool Undo()
    {
        // Заглушка для 1-й недели:
        // Механизм отката через стек истории снимков Memento реализуется на 6-й неделе.
        return false;
    }

    /// <summary>
    /// Возвращает текущий полный снимок игры (GameState) для отрисовки в консоли или сохранения.
    /// Метод гарантирует безопасность: возвращает изолированную глубокую копию (Clone).
    /// </summary>
    /// <returns>Неизменяемый извне снимок текущего состояния партии.</returns>
    public GameState GetCurrentState()
    {
        // Синхронизируем массив клеток из Board в объект GameState
        _state.Board = _board.GetRawBoard();

        // Возвращаем глубокую копию (Clone), чтобы UI или Data-слой 
        // случайно не испортили данные внутри GameManager напрямую
        return _state.Clone();
    }

    /// <summary>
    /// Загружает ранее сохраненную партию из объекта GameState (переданного из Data-слоя).
    /// Полностью восстанавливает расстановку на поле, очередность и номер хода.
    /// </summary>
    /// <param name="state">Снимок игры, прочитанный из JSON-файла сохранения.</param>
    public void LoadState(GameState state)
    {
        // Создаем независимую копию переданного состояния
        _state = state.Clone();

        // Загружаем фишки в рабочую модель доски
        _board.LoadFrom(_state.Board);
    }
}