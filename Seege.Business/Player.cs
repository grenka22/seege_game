using Seega.Contracts;

namespace Seega.Business;

/// <summary>
/// Доменная модель игрока в слое бизнес-логики (BL).
/// Хранит текущее состояние конкретного участника: имя, идентификатор и баланс фишек.
/// </summary>
public class Player
{
    /// <summary>
    /// Идентификатор игрока (Player1 или Player2).
    /// Определяет цвет фишек ('X' или 'O') и принадлежность клеток на доске.
    /// </summary>
    public PlayerId Id { get; set; }

    /// <summary>
    /// Отображаемое имя игрока (вводится пользователем в интерфейсе).
    /// Используется для вывода в консоль, сохранения партии и записи в таблицу рекордов.
    /// </summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>
    /// Количество фишек в запасе, которые игроку осталось выставить на доску в Фазе 1 (Расстановка).
    /// В начале игры равно 12. По мере выставления фишек уменьшается до 0.
    /// </summary>
    public int PiecesToPlace { get; set; } = 12;

    /// <summary>
    /// Текущее количество активных ("живых") фишек игрока на игровом поле.
    /// В фазе расстановки увеличивается от 0 до 12.
    /// В фазе движения уменьшается, когда соперник совершает захват.
    /// Если это число становится меньше или равно 1, игроку засчитывается поражение.
    /// </summary>
    public int PiecesOnBoard { get; set; } = 0;
}